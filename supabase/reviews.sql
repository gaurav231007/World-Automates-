-- Run once in Supabase SQL Editor.
create table if not exists public.reviews (
  id bigint generated by default as identity primary key,
  name text not null check (char_length(name) between 2 and 80),
  email text not null,
  rating int not null check (rating between 1 and 5),
  title text not null,
  body text not null,
  status text not null default 'pending' check (status in ('pending','approved','rejected')),
  created_at timestamptz not null default now()
);
create index if not exists reviews_status_created_idx on public.reviews(status, created_at desc);
alter table public.reviews enable row level security;
-- No anon/authenticated table policies: all reads/writes go through the server API using the service role key.


-- World Automates Studio OS: website enquiries / lead inbox
create table if not exists public.leads (
  id bigint generated by default as identity primary key,
  name text not null,
  email text not null,
  service text not null,
  details text default '',
  status text not null default 'new' check (status in ('new','contacted','qualified','closed')),
  created_at timestamptz not null default now()
);
alter table public.leads enable row level security;
-- Access is server-side only through the Supabase service-role key in Vercel.

-- Editable website content managed from the private admin panel.
create table if not exists public.site_settings (
 key text primary key,
 value text not null,
 updated_at timestamptz not null default now()
);
alter table public.site_settings enable row level security;


-- Team accounts and roles. Auth identities are managed through Supabase Auth.
create table if not exists public.team_members (
  user_id uuid primary key references auth.users(id) on delete cascade,
  full_name text not null,
  email text not null unique,
  role text not null check (role in ('manager','sales','developer','viewer')),
  active boolean not null default true,
  created_at timestamptz not null default now()
);
alter table public.team_members enable row level security;
-- No direct client policies. Team administration is performed by trusted server routes only.


-- Studio projects and employee task assignments
create table if not exists public.projects (
 id bigint generated by default as identity primary key,
 name text not null,
 client_name text default '',
 description text default '',
 status text not null default 'active' check (status in ('active','on_hold','completed','cancelled')),
 due_date date,
 created_at timestamptz not null default now()
);
create table if not exists public.tasks (
 id bigint generated by default as identity primary key,
 project_id bigint references public.projects(id) on delete set null,
 title text not null,
 description text default '',
 assigned_to uuid references public.team_members(user_id) on delete set null,
 status text not null default 'todo' check (status in ('todo','in_progress','blocked','done')),
 priority text not null default 'normal' check (priority in ('low','normal','high','urgent')),
 due_date date,
 created_at timestamptz not null default now(),
 updated_at timestamptz not null default now()
);
create index if not exists tasks_assigned_status_idx on public.tasks(assigned_to,status);
alter table public.projects enable row level security;
alter table public.tasks enable row level security;
-- All project/task access is performed by the server API after role verification.
